# 行业取值不可能写死：真实 A 股的行业分类随数据源更新而变。
# 由 `alphaforge_data` 落库后调用 `set_industries()` 注入，字段元数据再读它。
_INDUSTRY_VALUES: tuple[str, ...] = ()


def set_industries(values: object) -> None:
    """注入行业可选值。数据层同步完成后调用一次即可。"""
    global _INDUSTRY_VALUES
    cleaned = {str(v).strip() for v in (values or ()) if str(v).strip()}
    _INDUSTRY_VALUES = tuple(sorted(cleaned))


def industry_values() -> tuple[str, ...]:
    return _INDUSTRY_VALUES


def _resolve_options(f: Field) -> tuple[str, ...]:
    if f.options_source == "industry":
        return _INDUSTRY_VALUES
    return f.options


def resolve_industry(token: str) -> str | None:
    """口语 → 真实行业名。

    匹配顺序：全等 → 别名关键词 → 行业名包含关键词 → 关键词包含行业名。
    最后一步是为了「新能源光伏设备」这种用户把两个概念连写的句子。
    """
    t = (token or "").strip()
    if not t:
        return None
    values = _INDUSTRY_VALUES
    if not values:
        return None
    if t in values:
        return t

    keyword = INDUSTRY_ALIAS.get(t, t)
    if keyword in values:
        return keyword

    cands = [v for v in values if keyword in v]
    if not cands:
        cands = [v for v in values if v and v.rstrip("ⅡⅢ") in keyword]
    if not cands:
        cands = [v for v in values if keyword[:2] in v] if len(keyword) >= 2 else []
    if not cands:
        return None
    # 同长度取字典序，否则取最短的那个（「银行Ⅱ」优于「银行Ⅱ及其他」）
    return sorted(cands, key=lambda v: (len(v), v))[0]


def industry_keywords() -> tuple[str, ...]:
    """自然语言解析时优先尝试的行业词，长的在前，避免「酒」抢了「白酒」。"""
    words = set(INDUSTRY_ALIAS) | set(_INDUSTRY_VALUES)
    return tuple(sorted(words, key=lambda w: (-len(w), w)))


