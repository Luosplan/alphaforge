def field_meta() -> list[dict]:
    """给前端条件构造器用的字段元数据。"""
    return [
        {
            "key": f.key,
            "label": f.label,
            "unit": f.unit,
            "kind": f.kind,
            "desc": f.desc,
            "group": f.group,
            "ops": list(f.ops),
            "direction": f.direction,
            "direction_hint": "越大越好" if f.direction > 0 else "越小越好",
            "aliases": list(f.aliases),
            "options": list(_resolve_options(f)),
            # 是否可参与因子加权：前端策略编辑器据此决定要不要给出权重滑杆
            "weightable": f.key in WEIGHTABLE_FIELDS,
        }
        for f in FIELDS
    ]
